"use client";

import { useStore } from "./store";
import { QrImage } from "./Qr";
import { fmtDateTime, peso } from "@/lib/format";

/**
 * Hidden print surface. When a print job is set, only this area is visible to
 * the printer (see the @media print rules in globals.css): either a POS
 * receipt for one sale, or a sheet of QR labels.
 */
export function PrintHost() {
  const { data, printJob } = useStore();
  const { settings } = data;

  if (!printJob) return <div className="print-area" />;

  if (printJob.kind === "receipt") {
    const sale = data.sales.find((s) => s.id === printJob.saleId);
    if (!sale) return <div className="print-area" />;
    return (
      <div className="print-area">
        <div style={{ maxWidth: 320, margin: "0 auto", fontFamily: "monospace", fontSize: 12 }}>
          <div style={{ textAlign: "center", marginBottom: 8 }}>
            <div style={{ fontSize: 16, fontWeight: 700 }}>{settings.storeName}</div>
            {settings.address && <div>{settings.address}</div>}
            {settings.phone && <div>Tel: {settings.phone}</div>}
            <div style={{ marginTop: 4, fontWeight: 700 }}>OFFICIAL RECEIPT</div>
            <div>{sale.orNumber}</div>
          </div>
          <div style={{ borderTop: "1px dashed #000", paddingTop: 6 }}>
            <div>Date: {fmtDateTime(sale.createdAt, settings)}</div>
            <div>Cashier: {sale.cashier}</div>
            <div>Customer: {sale.customerType}</div>
          </div>
          <table style={{ width: "100%", marginTop: 8, borderCollapse: "collapse" }}>
            <tbody>
              {sale.items.map((it) => (
                <tr key={it.id}>
                  <td style={{ padding: "2px 0" }}>
                    {it.productName}
                    <div style={{ fontSize: 11 }}>
                      {it.qtyUnits} {it.unitName} × {peso(it.unitPrice)}
                    </div>
                  </td>
                  <td style={{ textAlign: "right", verticalAlign: "top", padding: "2px 0" }}>
                    {peso(it.lineTotal)}
                  </td>
                </tr>
              ))}
            </tbody>
          </table>
          <div style={{ borderTop: "1px dashed #000", marginTop: 8, paddingTop: 6 }}>
            <div style={{ display: "flex", justifyContent: "space-between" }}>
              <span>Subtotal</span>
              <span>{peso(sale.subtotal)}</span>
            </div>
            {sale.discountAmount > 0 && (
              <div style={{ display: "flex", justifyContent: "space-between" }}>
                <span>Discount ({sale.customerType})</span>
                <span>−{peso(sale.discountAmount)}</span>
              </div>
            )}
            <div style={{ display: "flex", justifyContent: "space-between", fontWeight: 700, fontSize: 14 }}>
              <span>TOTAL</span>
              <span>{peso(sale.total)}</span>
            </div>
            <div style={{ display: "flex", justifyContent: "space-between" }}>
              <span>{sale.paymentMethod === "GCash" ? "GCash" : "Cash tendered"}</span>
              <span>{peso(sale.amountTendered)}</span>
            </div>
            <div style={{ display: "flex", justifyContent: "space-between" }}>
              <span>Change</span>
              <span>{peso(sale.changeDue)}</span>
            </div>
          </div>
          <div style={{ textAlign: "center", marginTop: 10 }}>
            <div>Thank you for shopping!</div>
            <div style={{ fontSize: 11 }}>This receipt is generated by {settings.storeName}.</div>
          </div>
        </div>
      </div>
    );
  }

  const products = data.products.filter((p) => printJob.productIds.includes(p.id));
  return (
    <div className="print-area">
      <div style={{ display: "grid", gridTemplateColumns: "repeat(3, 1fr)", gap: 12 }}>
        {products.map((p) => (
          <div
            key={p.id}
            style={{
              border: "1px solid #999",
              borderRadius: 8,
              padding: 10,
              textAlign: "center",
              pageBreakInside: "avoid",
            }}
          >
            <div style={{ display: "flex", justifyContent: "center" }}>
              <QrImage value={p.code} size={110} />
            </div>
            <div style={{ fontWeight: 700, fontSize: 13, marginTop: 4 }}>{p.name}</div>
            <div style={{ fontSize: 11 }}>{p.code}</div>
            <div style={{ fontSize: 12, fontWeight: 600 }}>{peso(p.sellingPrice)}</div>
          </div>
        ))}
      </div>
    </div>
  );
}
